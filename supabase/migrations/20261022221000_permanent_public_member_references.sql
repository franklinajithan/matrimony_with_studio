create table if not exists public.member_public_references (
 member_id uuid primary key references public.profiles(id) on delete cascade,
 number bigint generated by default as identity unique not null
);
revoke all on public.member_public_references from anon,authenticated,public;
insert into public.member_public_references(member_id)
select id from public.profiles on conflict(member_id) do nothing;
create or replace function public.assign_member_public_reference() returns trigger
language plpgsql security definer set search_path = ''
as $$ begin insert into public.member_public_references(member_id) values(new.id) on conflict do nothing; return new; end $$;
drop trigger if exists assign_member_public_reference_on_create on public.profiles;
create trigger assign_member_public_reference_on_create after insert on public.profiles for each row execute function public.assign_member_public_reference();
create or replace function public.discovery_member_references()
returns table(member_id uuid, reference text)
language sql stable security definer set search_path = ''
as $$
 select r.member_id, 'CM-' || lpad(r.number::text,6,'0')
 from public.member_public_references r join public.profiles p on p.id=r.member_id
 where auth.uid() is not null and private.account_session_active()
   and p.is_published = true and p.suspended_at is null and public.member_is_active(p.id)
$$;
revoke all on function public.discovery_member_references() from public,anon;
grant execute on function public.discovery_member_references() to authenticated;